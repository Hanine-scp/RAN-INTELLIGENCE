export type AuthKey = keyof (typeof authTranslations)["Français"];

export function authT(locale: Locale, key: AuthKey): string {
  return authTranslations[locale][key] ?? authTranslations.Français[key];
}

export function formatAuthDevHints(locale: Locale, email?: string, sms?: string): string {
  const parts = [
    email ? `${authT(locale, "auth_dev_email_code")}: ${email}` : "",
    sms ? `${authT(locale, "auth_dev_sms_code")}: ${sms}` : "",
  ].filter(Boolean);
  return parts.join("  ·  ");
}
