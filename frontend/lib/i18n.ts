function humanizeColumnKey(key: string, locale: Locale): string {
  const parts = key.replace(/_/g, " ").trim().split(/\s+/);
  if (locale === "Français") {
    return parts.map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join(" ");
  }
  return parts.map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join(" ");
}

export function columnLabel(locale: Locale, key: string): string {
  const normalized = key.toLowerCase().trim();
  return COLUMN_LABELS[locale][normalized] ?? humanizeColumnKey(normalized, locale);
}

export function cellValueLabel(locale: Locale, column: string, value: unknown): string | null {
  const text = String(value ?? "").trim();
  if (!text) return null;
  const normalizedColumn = column.toLowerCase();
  const map = CELL_VALUE_LABELS[locale][normalizedColumn];
  if (!map) return null;
  return map[text] ?? map[text.toUpperCase()] ?? map[text.toLowerCase()] ?? null;
}
